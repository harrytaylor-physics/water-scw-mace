def functional_sensitivity() -> dict:
    """Stretch-band positions under LDA and hybrid labels, from the pulled docs."""
    doc = (ARC / "water-scw-mace" / "docs" / "LDA_CAMPAIGN.md").read_text()
    points = [
        {"T_K": 1000.0, "rho_kg_m3": 129.7,
         "stretch_peak_lda_cm": 3654.0, "stretch_peak_hybrid_cm": 3800.0,
         "note": "quoted as '3654 vs ~3800 at 1000 K'; the hybrid value is approximate"},
        {"T_K": 2000.0, "rho_kg_m3": 500.0,
         "stretch_peak_lda_cm": 3550.0, "stretch_peak_hybrid_cm": 3750.0,
         "note": "quoted as '3550 vs ~3750 at 2000 K'; the hybrid value is approximate"},
        {"T_K": 3000.0, "rho_kg_m3": 108.8, "achieved_T_K": 2807.0,
         "stretch_peak_lda_cm": None, "stretch_peak_hybrid_cm": None,
         "note": ("the third comparison point; the pulled documentation gives no "
                  "stretch-peak pair for it. Its thermostat handoff failed three "
                  "draws and the shipped run achieved 2807 K, used in the quantum "
                  "correction and the Planck weighting")},
    ]
    for p in points:
        lo, hi = p["stretch_peak_lda_cm"], p["stretch_peak_hybrid_cm"]
        p["red_shift_cm"] = (hi - lo) if (lo and hi) else None
    return {
        "points": points,
        # The documentation states the shift as "150-200 cm^-1"; the two peak
        # pairs it also quotes give 146 and 200. Both are recorded, distinguished,
        # rather than one silently standing for the other.
        "red_shift_range_cm_quoted": [150.0, 200.0],
        "red_shift_range_cm_from_quoted_peaks": [146.0, 200.0],
        "kappa_P_and_kappa_R": None,
        "kappa_blocked_reason": (
            "two independent reasons. (1) No LDA or hybrid spectra are in the pull — "
            "lda_campaign/ holds only scripts (make_opacity_lda.py, "
            "compare_point_full.py) and no spectral arrays. (2) The LDA documentation "
            "states that LDA absolute band intensities and kappa_R are "
            "floor-limited and are NOT quoted: the measured white floor is 0.6-2.6% "
            "of peak spectral density and only band positions and the libration "
            "region (40-60x floor) are quotable. Recomputing a mean from a "
            "floor-limited spectrum would produce a number that documentation "
            "itself declines to quote."),
        "files_needed": [
            "the per-point LDA spectra written by lda_campaign/stepG_dipoles/"
            "make_opacity_lda.py (kappa(nu) arrays, one per comparison point)",
            "the matching hybrid spectra at the same three states",
            "or the comparison output of lda_campaign/stepG_dipoles/"
            "compare_point_full.py, which computes both sides",
        ],
        "source_files": ["ed_data/arc/water-scw-mace/docs/LDA_CAMPAIGN.md"],
        "other_lda_numbers": {
            "held_out_parity_meV_per_A": {"bulk": 12.3, "rcb": 20.2,
                                          "note": "LDA model; the hybrid v4 "
                                                  "reference is 41/58"},
            "eos_lda_below_hybrid_mean_pct": -47.0,
            "eos_lda_below_hybrid_range_pct": [-0.5, -90.0],
            "nve_drift_max_meV_per_atom_per_ps": 0.017,
            "emissivity_planck_both_functionals": [0.994, 1.000],
        },
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("config", type=Path)
    args = ap.parse_args(argv)
    cfg = load_config(args.config)

    t1 = table1(cfg)
    t2 = table2(cfg)
    fs = functional_sensitivity()

    print(f"\n  ED TABLE 1 — {t1['n_rows']} state points, "
          f"{t1['n_with_pokazatel']} with POKAZATEL")
    print(f"    kappa_P {t1['kappa_P_range_cm2_g'][0]:.4g}-"
          f"{t1['kappa_P_range_cm2_g'][1]:.4g}, kappa_R "
          f"{t1['kappa_R_range_cm2_g'][0]:.4g}-{t1['kappa_R_range_cm2_g'][1]:.4g} cm^2/g")
    print(f"    wrote {', '.join(t1['files'])}")
    print(f"\n  ED TABLE 2 — {t2['n_rows']} boundaries "
          f"({t2['n_interpolated']} interpolated, {t2['n_clamped']} clamped)")
    print(f"    dispute ratio {t2['ratio_range'][0]:.3g}-{t2['ratio_range'][1]:.3g}, "
          f"flip threshold {t2['flip_threshold_range'][0]:.4g}-"
          f"{t2['flip_threshold_range'][1]:.4g}")
    print(f"    wrote {', '.join(t2['files'])}")

    print(f"\n  FUNCTIONAL SENSITIVITY (from the pulled LDA documentation)")
    head = (f"    {'T (K)':>7s} {'rho':>7s} | {'LDA peak':>9s} {'hybrid peak':>12s} "
            f"{'red shift':>10s}")
    print(head)
    print("    " + "-" * (len(head) - 4))
    for p in fs["points"]:
        lo, hi, d = (p["stretch_peak_lda_cm"], p["stretch_peak_hybrid_cm"],
                     p["red_shift_cm"])
        t_show = f"{p['T_K']:.0f}" + (f" ({p['achieved_T_K']:.0f})"
                                      if p.get("achieved_T_K") else "")
        print(f"    {t_show:>7s} {p['rho_kg_m3']:>7.4g} | "
              f"{('%.0f' % lo) if lo else 'not in pull':>9s} "
              f"{(('~%.0f' % hi) if hi else 'not in pull'):>12s} "
              f"{(('%.0f cm^-1' % d) if d else '-'):>10s}")
    print(f"\n    kappa_P / kappa_R under each functional: NOT AVAILABLE.")
    print(f"    {fs['kappa_blocked_reason']}")
    print(f"    files needed:")
    for f in fs["files_needed"]:
        print(f"      - {f}")

    led = ED_DIR / "ed_numbers.json"
    doc = json.loads(led.read_text()) if led.exists() else {}
    doc["ed_table1"] = t1
    doc["ed_table2"] = t2
    doc["functional_sensitivity"] = fs
    led.write_text(json.dumps(doc, indent=1) + "\n")
    print(f"\n  merged into {led}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
