def _sig(v, n=3, tex=False):
    """n significant figures, trailing zeros kept — %g strips them, which leaves a
    column reading 0.4 next to 0.504 and hides how many digits are meant."""
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return ""
    v = float(v)
    if v == 0.0:
        return "0." + "0" * (n - 1)
    from math import floor, log10

    exp = int(floor(log10(abs(v))))
    if exp >= 5 or exp <= -3:
        # far from unity a fixed-point render is a run of zeros or every digit of
        # a large integer, neither of which is n significant figures.
        m = v / 10.0 ** exp
        return (rf"${m:.{n - 1}f} \times 10^{{{exp}}}$" if tex
                else f"{v:.{n}g}")
    dec = n - 1 - exp
    if dec <= 0:
        # round to n figures first: "%.0f" of 1224.7 would print four of them.
        return f"{round(v, dec):.0f}"
    return f"{v:.{dec}f}"


def _tex(path: Path, header: list[str], rows: list[list[str]], caption: str) -> None:
    col = "l" * 1 + "r" * (len(header) - 1)
    out = ["% generated by figures/ed_tables.py — do not edit by hand",
           f"% {caption}",
           r"\begin{tabular}{" + col + "}", r"\toprule",
           " & ".join(header) + r" \\", r"\midrule"]
    out += [" & ".join(r) + r" \\" for r in rows]
    out += [r"\bottomrule", r"\end{tabular}"]
    path.write_text("\n".join(out) + "\n")


