def table2(cfg: Config) -> dict:
    flip = list(csv.DictReader((cfg.output_path / "S8_rcb_flip.csv").open()))
    flip.sort(key=lambda r: -float(r["fp_over_hitemp"]))

    header = ["case", "T (K)", r"$\rho$", "P (Pa)", r"$\kappa_R$ HIT",
              r"$\kappa_R$ FP", "ratio", "flip", "shift (dex)", r"$\Delta m$",
              "provenance"]
    csv_header = ["t_eq_k", "mass_core_mearth", "wmf", "t_int_k", "T_K",
                  "rho_kg_m3", "P_Pa", "kappa_R_hitemp_cm2_g", "kappa_R_fp_cm2_g",
                  "ratio", "flip_threshold", "shift_dex", "enclosed_mass_change",
                  "first_principles_provenance"]
    csv_rows, tex_rows = [], []
    for r in flip:
        m = re.search(r"M_c=(\S+)\s+wmf=(\S+)\s+T_eq=(\S+)\s+T_int=(\S+)", r["case"])
        mc, wmf, teq, tint = (m.groups() if m else ("", "", "", ""))
        clamped = r["fp_clamped_at_rcb"] == "True"
        in_box = r["in_fp_box"] == "True"
        # Named as ED Fig. 6a and main Fig. 4 name the same four categories, so a
        # reader can move between them: inside the box but outside the hull is
        # "between computed points".
        prov = ("clamped — between computed points (inside the grid box, outside "
                "its convex hull)" if clamped and in_box
                else "clamped — outside the grid box" if clamped
                else "interpolated")
        csv_rows.append([teq, mc, wmf, tint, f"{float(r['t_k']):.6g}",
                         f"{float(r['rho_si']):.6g}", f"{float(r['p_pa']):.6g}",
                         f"{float(r['kappa_r_hitemp_cm2_g']):.6g}",
                         f"{float(r['kappa_r_fp_cm2_g']):.6g}",
                         f"{float(r['fp_over_hitemp']):.6g}",
                         f"{float(r['threshold_factor']):.6g}",
                         f"{float(r['d_log10_rho']):.6g}",
                         f"{float(r['d_enclosed_mass_fraction']):.6g}", prov])
        tex_rows.append([
            f"{teq} K, {mc} M$_\\oplus$, {wmf}, {tint} K",
            f"{float(r['t_k']):.1f}", _sig(float(r["rho_si"]), 4),
            _sig(float(r["p_pa"]), tex=True), _sig(float(r["kappa_r_hitemp_cm2_g"])),
            _sig(float(r["kappa_r_fp_cm2_g"])), _sig(float(r["fp_over_hitemp"])),
            _sig(float(r["threshold_factor"])), _sig(float(r["d_log10_rho"])),
            _sig(float(r["d_enclosed_mass_fraction"]), tex=True),
            "interp." if not clamped else
            "clamped, between pts" if in_box else "clamped, outside box"])

    with (ED_DIR / "ed_table2.csv").open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(csv_header)
        w.writerows(csv_rows)
    _tex(ED_DIR / "ed_table2.tex", header, tex_rows,
         "ED Table 2 — the ten strongest boundaries")
    ratios = [float(r["fp_over_hitemp"]) for r in flip]
    thr = [float(r["threshold_factor"]) for r in flip]
    return {"n_rows": len(flip), "columns": csv_header,
            "sorted_by": "dispute ratio, descending",
            "n_interpolated": sum(1 for r in flip
                                  if r["fp_clamped_at_rcb"] != "True"),
            "n_clamped": sum(1 for r in flip if r["fp_clamped_at_rcb"] == "True"),
            "ratio_range": [min(ratios), max(ratios)],
            "flip_threshold_range": [min(thr), max(thr)],
            "files": ["figs/ed/ed_table2.csv", "figs/ed/ed_table2.tex"]}


